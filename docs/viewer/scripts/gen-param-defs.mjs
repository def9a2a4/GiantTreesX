// Generates src/param-defs.js from Arbaro's Params.registerParams().
// Usage: node scripts/gen-param-defs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..', '..');
const src = readFileSync(join(repo, 'src/arbaro/java/net/sourceforge/arbaro/params/Params.java'), 'utf8');
const body = src.slice(src.indexOf('private void registerParams()'));
// strip line comments
const code = body.replace(/^\s*\/\/.*$/gm, '');

// Tokenize Java call arguments (strings, numbers, identifiers, + concatenation)
function parseArgs(s, start) {
  const args = [];
  let i = start, cur = [], depth = 0;
  while (i < s.length) {
    const ch = s[i];
    if (ch === '"') {
      let j = i + 1, str = '';
      while (s[j] !== '"') {
        if (s[j] === '\\') { const n = s[j + 1]; str += n === 'n' ? '\n' : n; j += 2; } else { str += s[j]; j++; }
      }
      cur.push({ str });
      i = j + 1;
      continue;
    }
    if (ch === '/' && s[i + 1] === '/') { while (i < s.length && s[i] !== '\n') i++; continue; }
    if (ch === '(') { depth++; cur.push({ raw: ch }); i++; continue; }
    if (ch === ')') {
      if (depth === 0) { args.push(cur); return { args, end: i + 1 }; }
      depth--; cur.push({ raw: ch }); i++; continue;
    }
    if (ch === ',' && depth === 0) { args.push(cur); cur = []; i++; continue; }
    if (/\s|\+/.test(ch)) { i++; continue; }
    let j = i;
    while (j < s.length && !/[\s,()+"]/.test(s[j])) j++;
    cur.push({ raw: s.slice(i, j) });
    i = j;
  }
  throw new Error('unterminated');
}
function val(tok) {
  if (tok.length && tok.every((t) => 'str' in t)) return tok.map((t) => t.str).join('');
  const raw = tok.map((t) => t.raw).join('');
  const map = {
    'Double.POSITIVE_INFINITY': Infinity, 'Double.NEGATIVE_INFINITY': -Infinity,
    'Integer.MAX_VALUE': 2147483647, 'Integer.MIN_VALUE': -2147483648,
  };
  if (raw in map) return map[raw];
  const n = Number(raw);
  if (!Number.isNaN(n)) return n;
  throw new Error('cannot eval ' + raw);
}

const defs = [];
let order = 1;
const re = /\b(intParam|shapeParam|dblParam|int4Param|dbl4Param|lshParam|woodTypeParam|strParam)\s*\(/g;
let m;
while ((m = re.exec(code))) {
  const kind = m[1];
  const { args, end } = parseArgs(code, m.index + m[0].length);
  re.lastIndex = end;
  const a = args.map(val);
  const strip = (h) => String(h).replace(/<br>\n?/g, '\n').replace(/<li>/g, '\n - ').replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').replace(/&deg;/g, '°').replace(/\n{2,}/g, '\n').trim();
  if (kind === 'int4Param' || kind === 'dbl4Param') {
    order++;
    const [name, min, max, d0, d1, d2, d3, group, shortDesc, longDesc] = a;
    for (let l = 0; l < 4; l++) {
      defs.push({ name: l + name.slice(1), base: name, type: kind === 'int4Param' ? 'int' : 'float', min, max, deflt: [d0, d1, d2, d3][l], group, level: l, order, shortDesc, longDesc: strip(longDesc) });
    }
  } else if (kind === 'intParam' || kind === 'shapeParam' || kind === 'dblParam') {
    const [name, min, max, deflt, group, shortDesc, longDesc] = a;
    defs.push({ name, type: kind === 'dblParam' ? 'float' : 'int', enum: kind === 'shapeParam' ? 'shape' : undefined, min, max, deflt, group, level: -999, order: order++, shortDesc, longDesc: strip(longDesc) });
  } else {
    const [name, deflt, group, shortDesc, longDesc] = a;
    defs.push({ name, type: 'string', enum: kind === 'lshParam' ? 'leafShape' : kind === 'woodTypeParam' ? 'woodType' : undefined, deflt, group, level: -999, order: order++, shortDesc, longDesc: strip(longDesc) });
  }
}

function enumItems(file) {
  const s = readFileSync(join(repo, 'src/arbaro/java/net/sourceforge/arbaro/params', file), 'utf8');
  const mm = /items\s*=\s*\{([^}]*)\}/.exec(s);
  return mm[1].split(',').map((x) => x.trim().replace(/^"|"$/g, ''));
}
const enums = {
  shape: enumItems('ShapeParam.java'),
  leafShape: enumItems('LeafShapeParam.java'),
  woodType: enumItems('WoodTypeParam.java'),
};

const ser = (v) => JSON.stringify(v, (k, x) => (x === Infinity ? '__INF__' : x === -Infinity ? '__NINF__' : x), 1)
  .replace(/"__INF__"/g, 'Infinity').replace(/"__NINF__"/g, '-Infinity');
const out = `// GENERATED by scripts/gen-param-defs.mjs from Arbaro Params.java - do not edit.\n` +
  `export const PARAM_DEFS = ${ser(defs)};\n\nexport const ENUMS = ${JSON.stringify(enums)};\n`;
writeFileSync(join(here, '..', 'src', 'param-defs.js'), out);
console.log(`wrote ${defs.length} param defs`);
